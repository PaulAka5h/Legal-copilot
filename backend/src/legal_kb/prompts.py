"""Prompt builder and Legal citation verifier.

Guarantees:
1. Citations are verified against actual retrieved metadata (Act, Year, Section).
2. Prevents AI hallucination: prompts explicitly mandate quoting verbatim provisions and citing only retrieved sources.
3. Language alignment: replies in Bengali when user asks in Bengali; replies in English when user asks in English.
4. Distinguishes current vs historical law.
5. Strict "Insufficient Evidence" response when relevant law is not retrieved.
"""

from typing import List, Tuple
from backend.src.legal_kb.schemas import LegalChunkPayload
from backend.src.legal_kb.vector_store import VectorSearchResult


class LegalCitationVerifier:
    """Validates citations generated by LLMs against retrieved chunks metadata."""

    @staticmethod
    def verify_citation(
        citation_act: str,
        citation_section: str,
        retrieved_chunks: List[LegalChunkPayload],
    ) -> Tuple[bool, str]:
        """Checks if a cited Act and Section exists within the retrieved evidence set."""
        clean_act = citation_act.lower().strip()
        clean_sec = citation_section.lower().strip()

        for chunk in retrieved_chunks:
            chunk_act = (chunk.act_name or "").lower().strip()
            chunk_sec = (chunk.section or "").lower().strip()
            prov_label = (chunk.provision_label or "").lower().strip()

            if (clean_act in chunk_act or chunk_act in clean_act) and (
                clean_sec == chunk_sec or f"section {clean_sec}" in prov_label or f"ধারা {clean_sec}" in prov_label
            ):
                return True, f"Verified against source: {chunk.source_url}"

        return False, "Citation could not be verified against retrieved legal provisions."


def build_legal_rag_prompt(
    query: str,
    retrieved_results: List[VectorSearchResult],
    language: str = "auto",
) -> str:
    """Builds an evidence-grounded prompt for the LLM."""
    if not retrieved_results:
        return (
            "System: You are an AI Legal Copilot for Bangladesh Law.\n"
            "There is INSUFFICIENT EVIDENCE in the retrieved knowledge base to answer this question. "
            "State clearly that no relevant statutory provisions were found in the database. "
            "Do NOT invent or guess any section numbers, acts, or penalties."
        )

    context_blocks = []
    for idx, res in enumerate(retrieved_results, start=1):
        c = res.chunk
        status_label = "Current Law (In Force)" if c.is_current else "Historical / Amended Law"
        context_blocks.append(
            f"--- [EVIDENCE {idx}] ---\n"
            f"Act: {c.act_name} ({c.act_year or 'N/A'})\n"
            f"Provision: {c.provision_label or 'N/A'} (Section {c.section or 'N/A'})\n"
            f"Status: {status_label}\n"
            f"Source URL: {c.source_url}\n"
            f"Content:\n{c.text}\n"
        )

    context_str = "\n".join(context_blocks)

    prompt = f"""You are the official Bangladesh AI Legal Decision-Support Copilot.
You must answer the user's legal question strictly using the provided EVIDENCE blocks below.

LEGAL GROUNDING RULES:
1. ONLY make claims directly supported by the text in the EVIDENCE blocks.
2. Every legal claim MUST cite the exact Act name, year, and Section/Sub-section from the metadata.
3. If the retrieved evidence does not contain the answer, state clearly: "Insufficient legal evidence in verified database."
4. DO NOT invent section numbers, fines, terms of imprisonment, or case citations.
5. If an evidence block is marked "Historical / Amended Law", explicitly notify the lawyer that this provision may not represent current law.
6. Language Rule: If the user query is in Bangla, respond in professional Bangla. If the user query is in English, respond in professional English.

RETRIEVED LEGAL EVIDENCE:
{context_str}

USER QUERY:
{query}

LEGAL RESPONSE:"""

    return prompt
